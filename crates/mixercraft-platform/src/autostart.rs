//! Starting the engine automatically with the user session.
//!
//! | OS | Mechanism | Notes |
//! |---|---|---|
//! | Windows | Task Scheduler task with a logon trigger | Starts earlier than the `Run` registry key (which Windows delays after login), no execution time limit, keeps running on battery, restarts on failure. No elevation needed: the task is created for the current user. |
//! | Linux | systemd user unit | Ordered after PipeWire and WirePlumber; PipeWire is per-session, so the engine cannot start before login. |
//! | macOS | LaunchAgent | Loaded into the user's GUI domain; restarted if it exits abnormally. |
//!
//! The desktop app can also open in the tray at sign-in ([`enable_app`]); it
//! then starts the engine itself. This uses a second Task Scheduler task and
//! is only available on Windows for now (macOS has a tray too but is not
//! wired up; Linux has no tray).
//!
//! The file contents (task XML, unit file, plist) are generated by pure
//! functions so they are unit-tested on every platform; only installing them
//! touches the system.

use std::path::{Path, PathBuf};
use std::process::Command;

/// Name of the Windows scheduled task that starts the engine.
pub const WINDOWS_TASK_NAME: &str = "MixerCraft Engine";
/// Name of the Windows scheduled task that opens the desktop app in the tray.
pub const WINDOWS_APP_TASK_NAME: &str = "MixerCraft";
/// Name of the systemd user unit.
pub const SYSTEMD_UNIT_NAME: &str = "mixercraft.service";
/// Label of the macOS LaunchAgent.
pub const LAUNCHD_LABEL: &str = "org.mixercraft.engine";

/// What to start.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AutostartSpec {
    /// Absolute path of the executable (`mixercraftd`, or the desktop app
    /// for [`enable_app`]).
    pub program: PathBuf,
    /// Extra command-line arguments (e.g. `--config <path>`).
    pub args: Vec<String>,
}

/// Whether autostart is registered.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AutostartState {
    /// Registered; `detail` names the mechanism and location.
    Enabled { detail: String },
    /// Not registered.
    Disabled,
}

/// Autostart failures.
#[derive(Debug, thiserror::Error)]
pub enum AutostartError {
    /// A file could not be written or removed.
    #[error("{context}: {source}")]
    Io {
        context: String,
        #[source]
        source: std::io::Error,
    },
    /// A system tool reported an error.
    #[error("{tool} failed: {message}")]
    Tool { tool: &'static str, message: String },
    /// The platform has no supported mechanism.
    #[error("autostart is not supported on this platform")]
    Unsupported,
}

fn io(context: impl Into<String>) -> impl FnOnce(std::io::Error) -> AutostartError {
    let context = context.into();
    move |source| AutostartError::Io { context, source }
}

/// Runs a system tool and turns a non-zero exit into an error.
#[allow(dead_code)] // unused on platforms without an implementation
fn run(tool: &'static str, args: &[&str]) -> Result<String, AutostartError> {
    let out = Command::new(tool).args(args).output().map_err(io(format!("cannot run {tool}")))?;
    if out.status.success() {
        Ok(String::from_utf8_lossy(&out.stdout).into_owned())
    } else {
        let mut message = String::from_utf8_lossy(&out.stderr).trim().to_owned();
        if message.is_empty() {
            message = String::from_utf8_lossy(&out.stdout).trim().to_owned();
        }
        Err(AutostartError::Tool { tool, message })
    }
}

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;").replace('\'', "&apos;")
}

/// Quotes one argument for a Windows command line (CommandLineToArgvW rules).
fn windows_quote(arg: &str) -> String {
    if !arg.is_empty() && !arg.contains([' ', '\t', '"']) {
        return arg.to_owned();
    }
    let mut out = String::from("\"");
    let mut backslashes = 0;
    for c in arg.chars() {
        match c {
            '\\' => backslashes += 1,
            '"' => {
                out.extend(std::iter::repeat_n('\\', backslashes * 2 + 1));
                out.push('"');
                backslashes = 0;
            }
            _ => {
                out.extend(std::iter::repeat_n('\\', backslashes));
                out.push(c);
                backslashes = 0;
            }
        }
    }
    out.extend(std::iter::repeat_n('\\', backslashes * 2));
    out.push('"');
    out
}

/// Task Scheduler definition of the engine task for `user` (`DOMAIN\name`).
#[must_use]
pub fn windows_task_xml(spec: &AutostartSpec, user: &str) -> String {
    task_xml(spec, user, "Starts the MixerCraft audio engine when you sign in.")
}

/// Task Scheduler definition of the app task (opens the desktop app in the
/// tray) for `user` (`DOMAIN\name`).
#[must_use]
pub fn windows_app_task_xml(spec: &AutostartSpec, user: &str) -> String {
    task_xml(spec, user, "Opens MixerCraft in the system tray when you sign in.")
}

fn task_xml(spec: &AutostartSpec, user: &str, description: &str) -> String {
    let args: Vec<String> = spec.args.iter().map(|a| windows_quote(a)).collect();
    format!(
        r#"<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>{description}</Description>
  </RegistrationInfo>
  <Triggers>
    <LogonTrigger>
      <Enabled>true</Enabled>
      <UserId>{user}</UserId>
    </LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>{user}</UserId>
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>false</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings>
      <StopOnIdleEnd>false</StopOnIdleEnd>
      <RestartOnIdle>false</RestartOnIdle>
    </IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>4</Priority>
    <RestartOnFailure>
      <Interval>PT1M</Interval>
      <Count>3</Count>
    </RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>{command}</Command>
      <Arguments>{arguments}</Arguments>
    </Exec>
  </Actions>
</Task>
"#,
        description = xml_escape(description),
        user = xml_escape(user),
        command = xml_escape(&spec.program.to_string_lossy()),
        arguments = xml_escape(&args.join(" ")),
    )
}

/// Quotes one argument for a systemd `ExecStart=` line.
fn systemd_quote(arg: &str) -> String {
    let escaped = arg.replace('\\', "\\\\").replace('"', "\\\"").replace('%', "%%").replace('$', "$$");
    format!("\"{escaped}\"")
}

/// systemd user unit.
#[must_use]
pub fn systemd_unit(spec: &AutostartSpec) -> String {
    let mut exec = systemd_quote(&spec.program.to_string_lossy());
    for a in &spec.args {
        exec.push(' ');
        exec.push_str(&systemd_quote(a));
    }
    format!(
        "[Unit]
Description=MixerCraft audio engine
Documentation=https://github.com/JustinSchweiger/MixerCraft
After=pipewire.service pipewire-pulse.service wireplumber.service
Wants=pipewire.service

[Service]
ExecStart={exec}
Restart=on-failure
RestartSec=2

[Install]
WantedBy=default.target
"
    )
}

/// macOS LaunchAgent property list.
#[must_use]
pub fn launchd_plist(spec: &AutostartSpec) -> String {
    let mut program = format!("    <string>{}</string>\n", xml_escape(&spec.program.to_string_lossy()));
    for a in &spec.args {
        program.push_str(&format!("    <string>{}</string>\n", xml_escape(a)));
    }
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>{LAUNCHD_LABEL}</string>
  <key>ProgramArguments</key>
  <array>
{program}  </array>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <dict>
    <key>SuccessfulExit</key>
    <false/>
  </dict>
  <key>ThrottleInterval</key>
  <integer>5</integer>
  <key>ProcessType</key>
  <string>Interactive</string>
</dict>
</plist>
"#
    )
}

fn xml_unescape(s: &str) -> String {
    s.replace("&lt;", "<").replace("&gt;", ">").replace("&quot;", "\"").replace("&apos;", "'").replace("&amp;", "&")
}

/// The program a Task Scheduler definition starts (`<Command>`).
#[must_use]
pub fn command_of_task_xml(xml: &str) -> Option<PathBuf> {
    let start = xml.find("<Command>")? + "<Command>".len();
    let len = xml[start..].find("</Command>")?;
    Some(PathBuf::from(xml_unescape(xml[start..start + len].trim().trim_matches('"'))))
}

/// The program a systemd unit written by [`systemd_unit`] starts.
#[must_use]
pub fn command_of_systemd_unit(unit: &str) -> Option<PathBuf> {
    let exec = unit.lines().find_map(|l| l.strip_prefix("ExecStart="))?;
    let quoted = exec.strip_prefix('"')?;
    let mut out = String::new();
    let mut chars = quoted.chars();
    while let Some(c) = chars.next() {
        match c {
            '\\' => out.extend(chars.next()),
            '"' => return Some(PathBuf::from(out.replace("%%", "%").replace("$$", "$"))),
            c => out.push(c),
        }
    }
    None
}

/// The program a LaunchAgent written by [`launchd_plist`] starts.
#[must_use]
pub fn command_of_launchd_plist(plist: &str) -> Option<PathBuf> {
    let rest = &plist[plist.find("<key>ProgramArguments</key>")?..];
    let start = rest.find("<string>")? + "<string>".len();
    let len = rest[start..].find("</string>")?;
    Some(PathBuf::from(xml_unescape(&rest[start..start + len])))
}

