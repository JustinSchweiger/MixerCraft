#[allow(dead_code)]
fn home() -> Result<PathBuf, AutostartError> {
    std::env::var_os("HOME").map(PathBuf::from).ok_or_else(|| AutostartError::Io {
        context: "HOME is not set".into(),
        source: std::io::Error::from(std::io::ErrorKind::NotFound),
    })
}

#[allow(dead_code)]
fn write_file(path: &Path, content: &str) -> Result<(), AutostartError> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(io(format!("cannot create {}", dir.display())))?;
    }
    std::fs::write(path, content).map_err(io(format!("cannot write {}", path.display())))
}

#[cfg(windows)]
mod imp {
    use super::*;

    fn user() -> String {
        let name = std::env::var("USERNAME").unwrap_or_default();
        match std::env::var("USERDOMAIN") {
            Ok(domain) if !domain.is_empty() => format!("{domain}\\{name}"),
            _ => name,
        }
    }

    fn register(task: &str, xml: &str) -> Result<(), AutostartError> {
        // schtasks expects the XML file in UTF-16 with a byte-order mark.
        let mut bytes = vec![0xFF, 0xFE];
        bytes.extend(xml.encode_utf16().flat_map(u16::to_le_bytes));
        let path = std::env::temp_dir().join(format!("mixercraft-task-{}.xml", std::process::id()));
        std::fs::write(&path, bytes).map_err(io("cannot write task definition"))?;
        let result = run("schtasks", &["/Create", "/TN", task, "/XML", &path.to_string_lossy(), "/F"]);
        let _ = std::fs::remove_file(&path);
        result.map(|_| ())
    }

    fn unregister(task: &str) -> Result<(), AutostartError> {
        if task_status(task)? == AutostartState::Disabled {
            return Ok(());
        }
        run("schtasks", &["/Delete", "/TN", task, "/F"]).map(|_| ())
    }

    fn task_status(task: &str) -> Result<AutostartState, AutostartError> {
        match run("schtasks", &["/Query", "/TN", task, "/FO", "LIST"]) {
            Ok(_) => Ok(AutostartState::Enabled { detail: format!("Task Scheduler: \"{task}\"") }),
            Err(AutostartError::Tool { .. }) => Ok(AutostartState::Disabled),
            Err(e) => Err(e),
        }
    }

    pub fn enable(spec: &AutostartSpec, start_now: bool) -> Result<(), AutostartError> {
        register(WINDOWS_TASK_NAME, &windows_task_xml(spec, &user()))?;
        if start_now {
            run("schtasks", &["/Run", "/TN", WINDOWS_TASK_NAME])?;
        }
        Ok(())
    }

    pub fn disable() -> Result<(), AutostartError> {
        unregister(WINDOWS_TASK_NAME)
    }

    fn task_command(task: &str) -> Result<Option<PathBuf>, AutostartError> {
        match run("schtasks", &["/Query", "/TN", task, "/XML", "ONE"]) {
            Ok(xml) => Ok(command_of_task_xml(&xml)),
            Err(AutostartError::Tool { .. }) => Ok(None),
            Err(e) => Err(e),
        }
    }

    pub fn registered_engine() -> Result<Option<PathBuf>, AutostartError> {
        task_command(WINDOWS_TASK_NAME)
    }

    pub fn registered_app() -> Result<Option<PathBuf>, AutostartError> {
        task_command(WINDOWS_APP_TASK_NAME)
    }

    pub fn status() -> Result<AutostartState, AutostartError> {
        task_status(WINDOWS_TASK_NAME)
    }

    pub fn enable_app(spec: &AutostartSpec) -> Result<(), AutostartError> {
        register(WINDOWS_APP_TASK_NAME, &windows_app_task_xml(spec, &user()))
    }

    pub fn disable_app() -> Result<(), AutostartError> {
        unregister(WINDOWS_APP_TASK_NAME)
    }

    pub fn app_status() -> Result<AutostartState, AutostartError> {
        task_status(WINDOWS_APP_TASK_NAME)
    }
}

#[cfg(target_os = "linux")]
mod imp {
    use super::*;

    fn unit_path() -> Result<PathBuf, AutostartError> {
        let base = match std::env::var_os("XDG_CONFIG_HOME") {
            Some(d) if !d.is_empty() => PathBuf::from(d),
            _ => home()?.join(".config"),
        };
        Ok(base.join("systemd/user").join(SYSTEMD_UNIT_NAME))
    }

    pub fn enable(spec: &AutostartSpec, start_now: bool) -> Result<(), AutostartError> {
        write_file(&unit_path()?, &systemd_unit(spec))?;
        run("systemctl", &["--user", "daemon-reload"])?;
        if start_now {
            run("systemctl", &["--user", "enable", "--now", SYSTEMD_UNIT_NAME])?;
        } else {
            run("systemctl", &["--user", "enable", SYSTEMD_UNIT_NAME])?;
        }
        Ok(())
    }

    pub fn disable() -> Result<(), AutostartError> {
        let path = unit_path()?;
        if path.exists() {
            run("systemctl", &["--user", "disable", "--now", SYSTEMD_UNIT_NAME])?;
            std::fs::remove_file(&path).map_err(io(format!("cannot remove {}", path.display())))?;
            run("systemctl", &["--user", "daemon-reload"])?;
        }
        Ok(())
    }

    pub fn registered_engine() -> Result<Option<PathBuf>, AutostartError> {
        let path = unit_path()?;
        Ok(std::fs::read_to_string(path).ok().and_then(|unit| command_of_systemd_unit(&unit)))
    }

    pub fn status() -> Result<AutostartState, AutostartError> {
        let path = unit_path()?;
        if !path.exists() {
            return Ok(AutostartState::Disabled);
        }
        let enabled = run("systemctl", &["--user", "is-enabled", SYSTEMD_UNIT_NAME]).is_ok();
        Ok(if enabled {
            AutostartState::Enabled { detail: format!("systemd user unit {}", path.display()) }
        } else {
            AutostartState::Disabled
        })
    }
    pub fn enable_app(_: &AutostartSpec) -> Result<(), AutostartError> {
        Err(AutostartError::Unsupported)
    }
    pub fn disable_app() -> Result<(), AutostartError> {
        Err(AutostartError::Unsupported)
    }
    pub fn app_status() -> Result<AutostartState, AutostartError> {
        Err(AutostartError::Unsupported)
    }
    pub fn registered_app() -> Result<Option<PathBuf>, AutostartError> {
        Err(AutostartError::Unsupported)
    }
}

#[cfg(target_os = "macos")]
mod imp {
    use super::*;

    fn plist_path() -> Result<PathBuf, AutostartError> {
        Ok(home()?.join("Library/LaunchAgents").join(format!("{LAUNCHD_LABEL}.plist")))
    }

    fn domain() -> Result<String, AutostartError> {
        Ok(format!("gui/{}", run("id", &["-u"])?.trim()))
    }

    pub fn enable(spec: &AutostartSpec, _start_now: bool) -> Result<(), AutostartError> {
        let path = plist_path()?;
        let domain = domain()?;
        // Replace a previously loaded definition.
        let _ = run("launchctl", &["bootout", &format!("{domain}/{LAUNCHD_LABEL}")]);
        write_file(&path, &launchd_plist(spec))?;
        run("launchctl", &["bootstrap", &domain, &path.to_string_lossy()]).map(|_| ())
    }

    pub fn disable() -> Result<(), AutostartError> {
        let path = plist_path()?;
        if path.exists() {
            let _ = run("launchctl", &["bootout", &format!("{}/{LAUNCHD_LABEL}", domain()?)]);
            std::fs::remove_file(&path).map_err(io(format!("cannot remove {}", path.display())))?;
        }
        Ok(())
    }

    pub fn registered_engine() -> Result<Option<PathBuf>, AutostartError> {
        let path = plist_path()?;
        Ok(std::fs::read_to_string(path).ok().and_then(|plist| command_of_launchd_plist(&plist)))
    }

    pub fn status() -> Result<AutostartState, AutostartError> {
        let path = plist_path()?;
        Ok(if path.exists() {
            AutostartState::Enabled { detail: format!("LaunchAgent {}", path.display()) }
        } else {
            AutostartState::Disabled
        })
    }
    pub fn enable_app(_: &AutostartSpec) -> Result<(), AutostartError> {
        Err(AutostartError::Unsupported)
    }
    pub fn disable_app() -> Result<(), AutostartError> {
        Err(AutostartError::Unsupported)
    }
    pub fn app_status() -> Result<AutostartState, AutostartError> {
        Err(AutostartError::Unsupported)
    }
    pub fn registered_app() -> Result<Option<PathBuf>, AutostartError> {
        Err(AutostartError::Unsupported)
    }
}

